// Source-only isolated browser fixture: no full build or replacement product server.
import { createServer } from 'vite';
import react from '@vitejs/plugin-react';
import { chromium, expect } from '@playwright/test';
import { resolve } from 'node:path';
const root = resolve(import.meta.dirname, '..');
const server = await createServer({ configFile: false, root, optimizeDeps: { include: ['react', 'react-dom/client', 'zod'] }, plugins: [react(), { name: 'child-fixture', configureServer(server) { server.middlewares.use('/child-fixture', (_req, res) => { res.setHeader('content-type', 'text/html'); res.end('<div id="root"></div><script type="module">import RefreshRuntime from "/@react-refresh"; RefreshRuntime.injectIntoGlobalHook(window); window.$RefreshReg$ = () => {}; window.$RefreshSig$ = () => type => type; window.__vite_plugin_react_preamble_installed__ = true;</script><script type="module" src="/tests/fixtures/child-execution.tsx"></script>'); }); } }], resolve: { alias: { '@turnwire/sdk': resolve(root, 'packages/sdk/src/index.ts'), '@turnwire/protocol': resolve(root, 'packages/protocol/src/index.ts') } }, server: { host: '127.0.0.1', port: 0 } });
await server.listen();
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 430, height: 900 } });
const errors = []; page.on('pageerror', error => errors.push(error.message));
try {
  await page.goto(`http://127.0.0.1:${server.httpServer.address().port}/child-fixture`);
  const row = page.getByRole('button', { name: /Fixture child/ });
  await page.locator('.agent-strip-toggle').click();
  const assertLatestVisible = async () => {
    await expect.poll(() => page.locator('.child-records').evaluate(records => {
      const list = records.closest('.agent-list');
      return Math.abs(records.getBoundingClientRect().bottom - list.getBoundingClientRect().bottom);
    })).toBeLessThanOrEqual(2);
  };
  await row.click();
  await expect(page.locator('[data-record-id="answer"]')).toContainText('Execution snapshot 1');
  await assertLatestVisible();
  await expect(page.getByRole('button', { name: 'Refresh latest', exact: true })).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Return to latest (reset)', exact: true })).toHaveCount(0);
  const answer = page.locator('[data-record-id="answer"]');
  await expect(page.locator('.child-user')).toHaveCount(0);
  await expect(page.getByText('Delegated prompt stays in history', { exact: true })).toHaveCount(0);
  await expect(page.locator('.child-execution-heading, .child-execution-actions')).toHaveCount(0);
  await expect(answer.locator('.message-author, time')).toHaveCount(0);
  await expect(answer.locator('.markdown-body h1')).toHaveText('Shared heading');
  await expect(answer.locator('.markdown-body li')).toHaveCount(2);
  await expect(answer.locator('.markdown-body pre code')).toContainText('const safe');
  expect(await page.evaluate(() => window.childUnsafe)).toBeUndefined();
  expect(await answer.locator('.markdown-body').evaluate(node => getComputedStyle(node).fontSize)).toBe('12px');
  for (const selector of ['h1', 'li', 'pre code']) {
    const styles = await page.locator(`.main-reference .markdown-body ${selector}`).first().evaluate(node => ({ font: getComputedStyle(node).fontFamily, color: getComputedStyle(node).color }));
    expect(await answer.locator(`.markdown-body ${selector}`).first().evaluate(node => ({ font: getComputedStyle(node).fontFamily, color: getComputedStyle(node).color }))).toEqual(styles);
  }
  await expect(page.locator('.child-tool details, .child-tool summary, .child-tool pre')).toHaveCount(0);
  await expect(page.locator('[data-record-id="tool"] .tool-status')).toHaveText('Returned');
  await expect(page.getByText('actual tool output', { exact: true })).toHaveCount(0);
  await expect(page.locator('[data-record-id="tool"] .tool-action')).toHaveText('/workspace/example.ts');
  await expect(page.locator('[data-record-id="failed"] .tool-status')).toHaveText('Failed');
  await expect(page.locator('.child-tool-error')).toHaveText('Readable child error');
  await page.locator('.agent-list').evaluate(node => { node.scrollTop = 20; });
  const readingPosition = await page.locator('.agent-list').evaluate(node => node.scrollTop);
  await page.evaluate(() => { window.fixture.version = 2; });
  await expect(page.locator('[data-record-id="answer"]')).toContainText('Execution snapshot 2');
  expect(await page.locator('.agent-list').evaluate(node => node.scrollTop)).toBe(readingPosition);
  await expect(page.locator('[data-record-id="answer"]')).not.toContainText('Execution snapshot 1');
  await expect(page.getByRole('button', { name: 'Older page', exact: true })).toHaveCount(0);
  await expect(page.getByText('Latest output', { exact: true })).toBeVisible();
  expect(await page.evaluate(() => window.fixture.calls.every(call => call.limit === 50 && call.before === undefined && call.cursor === undefined))).toBe(true);
  await page.evaluate(() => { window.fixture.fail = true; });
  await expect(page.getByRole('alert')).toContainText('Stale execution');
  await page.evaluate(() => { window.fixture.fail = false; });
  await page.getByRole('button', { name: 'Retry', exact: true }).click();
  await expect(page.getByRole('alert')).toHaveCount(0);
  await page.getByRole('button', { name: 'Settle child', exact: true }).click();
  await expect(page.locator('.child-execution')).toBeVisible();
  await expect(page.locator('.agent-heading')).toHaveCount(0);
  await expect(page.locator('.child-execution-heading')).toHaveCount(0);
  await expect(page.locator('[data-record-id="answer"] .message-status')).toContainText('No result received');
  await expect(page.locator('[data-record-id="answer"] .message-status')).not.toContainText('In progress');
  await expect(page.locator('.child-record .cursor')).toHaveCount(0);
  await expect(page.locator('[data-record-id="pending"] .tool-status')).toHaveText('No result received');
  await expect(page.locator('[data-record-id="pending"] details, [data-record-id="pending"] pre')).toHaveCount(0);
  await row.click();
  await expect(row).toHaveCount(0);
  await expect(page.locator('.agent-strip')).toHaveCount(0);
  await page.getByRole('button', { name: 'Run child', exact: true }).click();
  await row.click();
  await expect(page.locator('.child-execution')).toBeVisible();
  await page.getByRole('button', { name: 'Toggle connection', exact: true }).click();
  await expect(page.getByText(/Offline — displayed execution/)).toBeVisible();
  await page.getByRole('button', { name: 'Toggle connection', exact: true }).click();
  await page.evaluate(() => { window.fixture.empty = true; });
  await expect(page.getByText('No execution output yet.', { exact: true })).toBeVisible();
  await row.click();
  await page.evaluate(() => { window.fixture.delay = 400; window.fixture.empty = false; });
  await row.click();
  await expect(page.getByText('Loading execution…', { exact: true })).toBeVisible();
  await row.click();
  await page.waitForTimeout(500);
  await expect(page.locator('.child-execution')).toHaveCount(0);
  await page.evaluate(() => { window.fixture.delay = 0; window.fixture.version = 3; });
  await row.click();
  await expect(page.locator('[data-record-id="answer"]')).toContainText('Execution snapshot 3');
  await assertLatestVisible();
  expect(errors).toEqual([]);
  console.log('Child browser fixture passed: Markdown, hidden delegated prompts, read-only tools/errors, latest50 replacement polling, no paging, scroll retention, retry, inactive retention, offline, empty.');
} finally { await browser.close(); await server.close(); }
